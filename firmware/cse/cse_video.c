{
    if (!frame) return;
    if ((unsigned)x >= CSE_LCD_WIDTH || (unsigned)y >= CSE_LCD_HEIGHT) return;
    frame[(size_t)y * CSE_LCD_WIDTH + x] = rgb565;
}

uint16_t cse_video_get_pixel(int x, int y)
{
    if (!frame || (unsigned)x >= CSE_LCD_WIDTH || (unsigned)y >= CSE_LCD_HEIGHT)
        return 0;
    return frame[(size_t)y * CSE_LCD_WIDTH + x];
}

/* Push the whole buffer through the GRAM window.  The address counter starts
 * at the window origin, so a plain sequential stream fills the panel. */
int cse_video_blit(const uint16_t *src)
{
    if (!lcd_ready) return -1;
    cse_lcd_write_reg(LCDR_CURSOR_ROW, 0);
    cse_lcd_write_reg(LCDR_CURSOR_COLUMN, 0);
    cse_port_out(PORT_LCD_CMD, LCDR_GRAM);
    cse_port_out(PORT_LCD_CMD, LCDR_GRAM);
    for (uint32_t i = 0; i < (uint32_t)CSE_LCD_WIDTH * CSE_LCD_HEIGHT; i++) {
        uint16_t px = src[i];
        cse_port_out(PORT_LCD_DATA, (uint8_t)(px >> 8));
        cse_port_out(PORT_LCD_DATA, (uint8_t)(px & 0xFF));
    }
    return 0;
}

/* Present the abstract RGB framebuffer produced by the virtual VGA.
 * Rows are bulk-converted (never per-pixel calls) then streamed. */
int cse_video_update(const uint8_t *fb, uint32_t w, uint32_t h)
{
    if (!lcd_ready || !frame || !fb || w == 0 || h == 0) return -1;

    uint32_t ystep = (h + CSE_LCD_HEIGHT - 1) / CSE_LCD_HEIGHT;
    uint32_t xstep = (w + CSE_LCD_WIDTH - 1) / CSE_LCD_WIDTH;

    for (uint32_t y = 0; y < CSE_LCD_HEIGHT; y++) {
        uint32_t sy = y * ystep;
        if (sy >= h) sy = h - 1;
        vga_rgb_row_to_rgb565(fb + (size_t)sy * w * 3, w,
                              frame + (size_t)y * CSE_LCD_WIDTH,
                              CSE_LCD_WIDTH, xstep);
    }
    return cse_video_blit(frame);
}

void cse_video_shutdown(void)
{
    if (lcd_ready) {
        cse_lcd_write_reg(LCDR_DISPCONTROL1, 0x0000);   /* display off */
        cse_backlight(0);
        lcd_ready = 0;
    }
}
