static void lcd_delay(void)
{
    for (volatile unsigned i = 0; i < 8192u; i++) { /* wait */ }
}

static void lcd_power_on(void)
{
    cse_lcd_write_reg(LCDR_DISPCONTROL1,   0x0000);
    cse_lcd_write_reg(LCDR_POWERCONTROL2,  0x0007);
    cse_lcd_write_reg(LCDR_POWERCONTROL3,  0x008C);
    cse_lcd_write_reg(LCDR_POWERCONTROL4,  0x1800);
    cse_lcd_write_reg(LCDR_POWERCONTROL7,  0x0030);
    lcd_delay();

    cse_lcd_write_reg(LCDR_POWERCONTROL1,  0x0190);
    cse_lcd_write_reg(LCDR_POWERCONTROL2,  0x0227);
    lcd_delay();

    cse_lcd_write_reg(LCDR_DRIVER_OUTCTRL1, 0x0000);
    cse_lcd_write_reg(LCDR_LCDDRIVING_CTRL, 0x0200);
    cse_lcd_write_reg(LCDR_ENTRYMODE,       0x10B8);
    cse_lcd_write_reg(LCDR_DISPCONTROL2,    0x0202);
    cse_lcd_write_reg(LCDR_DISPCONTROL3,    0x0000);
    cse_lcd_write_reg(LCDR_DISPCONTROL4,    0x0000);
    cse_lcd_write_reg(LCDR_RGBDISP_IFACE,   0x0000);
    cse_lcd_write_reg(LCDR_FRAMEMARKER,     0x0000);
    cse_lcd_write_reg(LCDR_GATESCAN_CTRL,   0x2700);
    cse_lcd_write_reg(LCDR_BASEIMAGE_CTRL,  0x0001);
    cse_lcd_write_reg(LCDR_VERTSCROLL_CTRL, 0x0000);
    cse_lcd_write_reg(LCDR_PANEL_IFACE1,    0x0010);
    cse_lcd_write_reg(LCDR_PANEL_IFACE2,    0x0600);
    cse_lcd_write_reg(LCDR_PANEL_IFACE4,    0x0200);
    cse_lcd_write_reg(LCDR_PANEL_IFACE5,    0x0C00);

    cse_lcd_write_reg(LCDR_GAMMA1,  0x0000);
    cse_lcd_write_reg(LCDR_GAMMA2,  0x0305);
    cse_lcd_write_reg(LCDR_GAMMA3,  0x0002);
    cse_lcd_write_reg(LCDR_GAMMA4,  0x0301);
    cse_lcd_write_reg(LCDR_GAMMA5,  0x0004);
    cse_lcd_write_reg(LCDR_GAMMA6,  0x0507);
    cse_lcd_write_reg(LCDR_GAMMA7,  0x0204);
    cse_lcd_write_reg(LCDR_GAMMA8,  0x0707);
    cse_lcd_write_reg(LCDR_GAMMA9,  0x0103);
    cse_lcd_write_reg(LCDR_GAMMA10, 0x0004);

    /* Full-screen window.  The panel is addressed 240 rows x 320 columns in
     * its native axis; the rotation mapping is a VERIFY item resolved during
     * on-device bring-up (see docs/CSE_MEMORY_MAP.md checklist). */
    cse_lcd_write_reg(LCDR_WIN_HORIZ_START, 0x0000);
    cse_lcd_write_reg(LCDR_WIN_HORIZ_END,   0x00EF);   /* 239 */
    cse_lcd_write_reg(LCDR_WIN_VERT_START,  0x0000);
    cse_lcd_write_reg(LCDR_WIN_VERT_END,    0x013F);   /* 319 */
    cse_lcd_write_reg(LCDR_FRAMERATE,       0x000B);

    cse_lcd_write_reg(LCDR_POWERCONTROL1, 0x1190);
    cse_lcd_write_reg(LCDR_DISPCONTROL1,  0x0001);
    lcd_delay(); lcd_delay();
    cse_lcd_write_reg(LCDR_DISPCONTROL1,  0x0023);
    lcd_delay(); lcd_delay();
    cse_lcd_write_reg(LCDR_DISPCONTROL1,  0x0133);     /* display on */
    cse_lcd_write_reg(LCDR_ENTRYMODE,     0x10B8);
}

