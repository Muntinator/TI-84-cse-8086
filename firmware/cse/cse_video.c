/*
 * Munt386-CSE -- CSE 320x240 RGB565 display backend.
 *
 * Pipeline (identical to the original port's architecture):
 *
 *     virtual VGA (src/vga.c, unchanged)
 *         -> abstract RGB framebuffer
 *             -> vga_rgb_row_to_rgb565() bulk row conversion
 *                 -> cse_video_update() GRAM streaming
 *                     -> LCD ports 0x10/0x11
 *
 * The virtual VGA is NOT modified for the CSE: it keeps its own resolution
 * and framebuffer; conversion and scaling happen entirely here.
 *
 * The LCD power-on sequence follows the documented CSE register order
 * (KnightOS display-color.asm; facts only).  The full-frame window is set
 * once and GRAM is streamed row-major, which is the fastest documented
 * bulk path -- individual pixels are written only through cse_video_set_pixel
 * (diagnostics), never in the frame path.
 *
 * cse_video_print_line() renders diagnostic text in 16x16 cells using the
 * project's own 8x8 font (the same public-domain data as src/font.c).
 */
#include "cse_hardware.h"
#include "cse_ports.h"
#include "cse_video.h"
#include "cse_main.h"
#include "platform.h"
#include "munt386.h"      /* vga_rgb_row_to_rgb565 */
#include <string.h>

