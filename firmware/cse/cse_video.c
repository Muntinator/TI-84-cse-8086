static uint16_t fg565 = 0xFFFF;   /* white     */
static uint16_t bg565 = 0x0008;   /* dark blue */

static void txt_blit_cell(int cx, int cy, uint8_t ch)
{
    if (ch < 0x20 || ch > 0x7E) ch = ' ';
    const uint8_t *glyph = diag_font[ch - 0x20];
    for (int gy = 0; gy < 8; gy++) {
        uint8_t bits = glyph[gy];
        for (int gx = 0; gx < 8; gx++) {
            uint16_t c = (bits & (0x80 >> gx)) ? fg565 : bg565;
            int px = cx * 16 + gx * 2;
            int py = cy * 16 + gy * 2;
            for (int dy = 0; dy < 2; dy++)
                for (int dx = 0; dx < 2; dx++)
                    cse_video_set_pixel(px + dx, py + dy, c);
        }
    }
}

void cse_video_print_line(const char *msg)
{
    if (!lcd_ready) return;
    int col = 0;
    for (const char *p = msg; *p && col < CSE_DIAG_COLS; p++, col++)
        txt_blit_cell(col, txt_row, (uint8_t)*p);
    for (; col < CSE_DIAG_COLS; col++)
        txt_blit_cell(col, txt_row, ' ');
    if (++txt_row >= CSE_DIAG_ROWS) txt_row = 0;
    cse_video_blit(frame);
}

/* One diagnostic line with cursor movement preserved; an empty msg moves
 * to the next row.  Named per cse_main.h. */
#ifdef MUNT386_DEVICE
/* Device build: no 150 KiB RGB565 shadow buffer exists (see cse_video_init).
 * The line is rasterised scanline-by-scanline directly into GRAM: the panel
 * cursor is reset to the window origin, then for each of the 16 scaled rows
 * every cell's glyph bits are streamed at 2x horizontal scale.  The static
 * row cursor carries between calls (never re-entrant). */
void cse_video_print(const char *msg)
{
    static int print_row;
    if (!lcd_ready) return;
    cse_lcd_write_reg(LCDR_CURSOR_ROW, 0);
    cse_lcd_write_reg(LCDR_CURSOR_COLUMN, 0);
    cse_port_out(PORT_LCD_CMD, LCDR_GRAM);
    cse_port_out(PORT_LCD_CMD, LCDR_GRAM);
    for (int gy = 0; gy < 16; gy++) {                    /* 2x-scaled rows */
        for (int rep = 0; rep < 2; rep++) {              /* 2x vertical scale */
            for (int col = 0; col < CSE_DIAG_COLS; col++) {
                uint8_t ch = (msg && msg[col]) ? (uint8_t)msg[col] : ' ';
                if (ch < 0x20 || ch > 0x7E) ch = ' ';
                uint8_t bits = diag_font[ch - 0x20][gy >> 1];
                for (int gx = 0; gx < 8; gx++) {
                    uint16_t c = (bits & (0x80 >> gx)) ? fg565 : bg565;
                    for (int dx = 0; dx < 2; dx++) {     /* 2x horizontal scale */
                        cse_port_out(PORT_LCD_DATA, (uint8_t)(c >> 8));
                        cse_port_out(PORT_LCD_DATA, (uint8_t)(c & 0xFF));
                    }
                }
            }
        }
    }
    if (++print_row >= CSE_DIAG_ROWS) print_row = 0;
}
#else
void cse_video_print(const char *msg)
{
    if (!lcd_ready) return;
    if (msg && *msg) {
        int col = 0;
        for (const char *p = msg; *p && col < CSE_DIAG_COLS; p++, col++)
            txt_blit_cell(col, txt_row, (uint8_t)*p);
        for (; col < CSE_DIAG_COLS; col++)
            txt_blit_cell(col, txt_row, ' ');
    }
    if (++txt_row >= CSE_DIAG_ROWS) txt_row = 0;
    cse_video_blit(frame);
}
#endif /* MUNT386_DEVICE */

