#ifdef MUNT386_DEVICE
/* Device build: clear the panel by streaming background pixels for one full
 * frame (no shadow buffer to blit). */
static void cse_video_clear_device(void)
{
    cse_lcd_write_reg(LCDR_CURSOR_ROW, 0);
    cse_lcd_write_reg(LCDR_CURSOR_COLUMN, 0);
    cse_port_out(PORT_LCD_CMD, LCDR_GRAM);
    cse_port_out(PORT_LCD_CMD, LCDR_GRAM);
    for (uint32_t i = 0; i < (uint32_t)CSE_LCD_WIDTH * CSE_LCD_HEIGHT; i++) {
        cse_port_out(PORT_LCD_DATA, (uint8_t)(bg565 >> 8));
        cse_port_out(PORT_LCD_DATA, (uint8_t)(bg565 & 0xFF));
    }
}
#endif

int cse_video_init(void)
{
#ifdef MUNT386_DEVICE
    /* No 150 KiB RGB565 shadow buffer on the device (docs/CSE_MEMORY_MAP.md
     * section 5): the frame is streamed to GRAM directly and the diagnostic
     * text rasterises scanline-by-scanline (cse_video_print). */
    frame = NULL;
    txt_row = 0;
    lcd_power_on();
    cse_backlight(1);
    lcd_ready = 1;
    cse_video_clear_device();
    return 0;
#else
    /* Always (re)allocate: after shutdown+arena-reset cycles the previous
     * pointer may have been consumed by a different arena user, and the
     * diagnostic tests verify pixel round-trips through this buffer. */
    if (frame) {
        platform_memory_free(frame,
            (size_t)CSE_LCD_WIDTH * CSE_LCD_HEIGHT * sizeof(uint16_t));
        frame = NULL;
    }
    frame = (uint16_t *)platform_memory_alloc(
        (size_t)CSE_LCD_WIDTH * CSE_LCD_HEIGHT * sizeof(uint16_t));
    if (!frame) return -1;
    memset(frame, 0, (size_t)CSE_LCD_WIDTH * CSE_LCD_HEIGHT * sizeof(uint16_t));

    txt_row = 0;
    lcd_power_on();
    cse_backlight(1);
    lcd_ready = 1;
    cse_video_blit(frame);
    return 0;
#endif
}

